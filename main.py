class DraggableWindow(tk.Tk):
    def __init__(self):
        super().__init__()
        self.overrideredirect(True)
        self.attributes("-alpha", 0.97)
        self._dx = self._dy = 0

    def create_title_bar(self, title_text):
        bar = tk.Frame(self, bg=BG2, height=32)
        bar.pack(fill=tk.X, side=tk.TOP)
        bar.pack_propagate(False)
        lbl = tk.Label(bar, text=title_text, bg=BG2, fg=FG, font=("Courier New", 10, "bold"))
        lbl.pack(side=tk.LEFT, padx=12)
        x = tk.Button(bar, text="✕", bg=BG2, fg=FG, bd=0, font=("Arial", 12, "bold"),
                      activebackground="#ffffff", activeforeground="#000000",
                      highlightthickness=0, cursor="hand2", padx=10,
                      command=lambda: (play("click"), self.after(120, self.destroy)))
        x.pack(side=tk.RIGHT)
        x.bind("<Enter>", lambda e: x.config(bg="#ffffff", fg="#000000"))
        x.bind("<Leave>", lambda e: x.config(bg=BG2, fg=FG))
        for w in (bar, lbl):
            w.bind("<Button-1>", self._press)
            w.bind("<B1-Motion>", self._drag)

    def _press(self, e):
        self._dx = e.x_root - self.winfo_x()
        self._dy = e.y_root - self.winfo_y()

    def _drag(self, e):
        self.geometry(f"+{e.x_root - self._dx}+{e.y_root - self._dy}")


