# ── Instant scanner: ONE pass over the file for ALL keywords ──────────────
import re
from collections import Counter

try:
    import numpy as np          # optional, makes big files scan ~5x faster
except Exception:
    np = None

def _load_extra_keywords():
    """Optional: put extra keywords (one per line) in keywords_extra.txt next to this script."""
    extra = []
    try:
        p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "keywords_extra.txt")
        if os.path.exists(p):
            with open(p, encoding="utf-8", errors="ignore") as f:
                extra = [l.strip().encode() for l in f if l.strip() and not l.startswith("#")]
    except Exception:
        pass
    return extra

def _trie_regex(words):
    """Every keyword compiled into one prefix-tree regex (longest match wins)."""
    trie = {}
    for w in words:
        node = trie
        for b in w:
            node = node.setdefault(b, {})
        node[None] = True
    def build(node):
        end = None in node
        kids = sorted(k for k in node if k is not None)
        parts = [re.escape(bytes([k])) + build(node[k]) for k in kids]
        if not parts:
            return b""
        body = parts[0] if len(parts) == 1 else b"(?:" + b"|".join(parts) + b")"
        return (b"(?:" + body + b")?") if end else body
    return re.compile(build(trie))

_ALL_KEYWORDS = list(dict.fromkeys(k for k in ANTI_CHEAT_KEYWORDS + _load_extra_keywords() if k))
_PATTERN = _trie_regex(_ALL_KEYWORDS)

# 3-byte-prefix lookup table so numpy can skip 99.98% of the file instantly
_TABLE = None
if np is not None:
    _TABLE = np.zeros(1 << 24, dtype=bool)
    for k in _ALL_KEYWORDS:
        if len(k) >= 3:
            _TABLE[(k[0] << 16) | (k[1] << 8) | k[2]] = True
        elif len(k) == 2:
            _TABLE[(k[0] << 16) + (k[1] << 8): (k[0] << 16) + (k[1] << 8) + 256] = True
        else:
            _TABLE[(k[0] << 16): (k[0] << 16) + 65536] = True

_CHUNK = 8 * 1024 * 1024

def iter_matches(data):
    """Yields (position, matched_bytes), non-overlapping, longest match first."""
    if _TABLE is None:
        for m in _PATTERN.finditer(data):
            if m.end() > m.start():
                yield m.start(), m.group()
        return
    n = len(data)
    free = 0                                   # first position not covered by a previous match
    for base in range(0, n, _CHUNK):
        end = min(n, base + _CHUNK + 2)        # +2 overlap so no triple is split across chunks
        a = np.frombuffer(data, dtype=np.uint8, count=end - base, offset=base)
        if len(a) < 3:
            break
        idx = (a[:-2].astype(np.uint32) << 16) | (a[1:-1].astype(np.uint32) << 8) | a[2:]
        for p in np.flatnonzero(_TABLE[idx]).tolist():
            pos = base + p
            if pos < free or pos >= base + _CHUNK:
                continue
            m = _PATTERN.match(data, pos)
            if m and m.end() > pos:
                free = m.end()
                yield pos, m.group()
    # the last 2 bytes can't start a full triple, so check them directly
    for pos in range(max(free, n - 2, 0), n):
        m = _PATTERN.match(data, pos)
        if m and m.end() > pos:
            free = m.end()
            yield pos, m.group()

def scan_bytes(data):
    hits = Counter()
    for _, s in iter_matches(data):
        hits[s] += 1
    return hits

def strip_bytes(data):
    """Zero every hit in place, in one pass. Returns (new_data, Counter)."""
    out = bytearray(data)
    hits = Counter()
    for pos, s in iter_matches(data):
        out[pos:pos + len(s)] = b"\x00" * len(s)
        hits[s] += 1
    return bytes(out), hits


# ── Sound engine (synthesized in memory, no audio files needed) ───────────
import io, math, struct, wave, sys

try:
    import winsound
except ImportError:
    winsound = None

def _tone_samples(freq, ms, vol=0.35, rate=22050):
    n = int(rate * ms / 1000)
    out = []
    for i in range(n):
        env = min(1.0, i / (rate * 0.005), (n - i) / (rate * 0.03))  # fade in/out = no clicks
        out.append(int(32767 * vol * env * math.sin(2 * math.pi * freq * i / rate)))
    return out

def _make_wav(notes, rate=22050):
    samples = []
    for freq, ms in notes:
        samples += _tone_samples(freq, ms, rate=rate) if freq else [0] * int(rate * ms / 1000)
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate)
        w.writeframes(struct.pack("<%dh" % len(samples), *samples))
    return buf.getvalue()

